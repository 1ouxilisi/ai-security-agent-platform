def _pad_controls(base: list[dict], framework: str, target: int,
                  pool: list[tuple[str, str, str, str, str]]) -> list[dict]:
    """按框架补足到目标数量：pool = (名称, 要求, 审计, 风险, 建议)。
    池用尽后以编号后缀生成唯一条目，避免死循环。"""
    out = [c for c in base if c["framework"] == framework]
    existing_names = {c["name"] for c in out}
    n = len(out)
    i = 0
    suffix = 1
    while n < target:
        name, req, audit, risk, advice = pool[i % len(pool)]
        i += 1
        if name in existing_names:
            # 名称已存在，追加编号后缀生成唯一条目
            suffix += 1
            cand = f"{name}({suffix})"
            if cand in existing_names:
                continue
            name = cand
        existing_names.add(name)
        n += 1
        out.append(_ctl(
            f"{framework.split('：')[0]}-PAD-{n:04d}", name, framework,
            "扩展控制", req, audit, risk, advice,
            framework))
    return out


