def generate_env_file(config: Optional[Dict[str, str]] = None) -> str:
    """生成 .env 文件内容。"""
    merged = {**CONFIG_TEMPLATE, **(config or {})}
    if merged.get("AI_HACKING_SECRET_KEY") in ("<auto-generated>", ""):
        merged["AI_HACKING_SECRET_KEY"] = secrets.token_hex(32)
    lines = [f"# Generated at {time.strftime('%Y-%m-%d %H:%M:%S')}", ""]
    for k, v in merged.items():
        lines.append(f"{k}={v}")
    return "\n".join(lines)


def validate_config(config: Dict[str, Any]) -> Dict[str, Any]:
    """验证配置项合法性。"""
    errors: List[str] = []
    warnings: List[str] = []

    port = config.get("AI_HACKING_PORT", "8000")
    try:
        p = int(port)
        if p < 1 or p > 65535:
            errors.append(f"端口 {p} 超出范围 (1-65535)")
    except (ValueError, TypeError):
        errors.append(f"端口不是数字: {port}")

    secret = config.get("AI_HACKING_SECRET_KEY", "")
    if len(secret) < 16:
        warnings.append("SECRET_KEY 长度小于 16 字节，生产环境建议 >= 32")
    if config.get("AI_HACKING_ENV") == "production" and config.get("AI_HACKING_DEBUG") == "true":
        errors.append("生产环境不应开启 DEBUG 模式")
    if config.get("AI_HACKING_ENV") == "production" and config.get("AI_HACKING_CORS_ORIGINS") == "*":
        warnings.append("生产环境 CORS 不应使用通配符 *")

    return {"valid": len(errors) == 0, "errors": errors, "warnings": warnings}


def backup_config(config: Dict[str, Any], label: str = "") -> Dict[str, Any]:
    """备份配置。"""
    snap = {
        "snapshot_id": hashlib.sha256(f"{time.time()}{label}".encode()).hexdigest()[:16],
        "label": label,
        "captured_at": time.strftime("%Y-%m-%d %H:%M:%S"),
        "config": config,
    }
    _CONFIG_HISTORY.append(snap)
    return {"ok": True, "snapshot_id": snap["snapshot_id"], "label": label}


def list_config_backups() -> List[Dict[str, Any]]:
    """列出配置备份。"""
    return [
        {"snapshot_id": s["snapshot_id"], "label": s["label"],
         "captured_at": s["captured_at"]}
        for s in reversed(_CONFIG_HISTORY)
    ]


def compare_configs(c1: Dict[str, Any], c2: Dict[str, Any]) -> Dict[str, Any]:
    """对比两份配置差异。"""
    all_keys = set(c1.keys()) | set(c2.keys())
    diffs: List[Dict[str, str]] = []
    for k in sorted(all_keys):
        v1 = c1.get(k, "<missing>")
        v2 = c2.get(k, "<missing>")
        if v1 != v2:
            diffs.append({"key": k, "old": str(v1), "new": str(v2)})
    return {"total_diff": len(diffs), "diffs": diffs}


