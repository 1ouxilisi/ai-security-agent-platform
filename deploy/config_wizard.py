def service_action(action: str) -> Dict[str, Any]:
    """模拟服务操作。"""
    action = action.lower()
    now = time.strftime("%Y-%m-%d %H:%M:%S")
    if action == "start":
        if _SERVICE_STATE["status"] == "running":
            return {"ok": False, "message": "服务已在运行"}
        _SERVICE_STATE["status"] = "running"
        _SERVICE_STATE["started_at"] = now
        _SERVICE_STATE["log_tail"].append(f"[{now}] INFO  Service started")
        return {"ok": True, "status": "running"}
    if action == "stop":
        _SERVICE_STATE["status"] = "stopped"
        _SERVICE_STATE["log_tail"].append(f"[{now}] INFO  Service stopped")
        return {"ok": True, "status": "stopped"}
    if action == "restart":
        _SERVICE_STATE["restart_count"] += 1
        _SERVICE_STATE["status"] = "running"
        _SERVICE_STATE["started_at"] = now
        _SERVICE_STATE["log_tail"].append(f"[{now}] INFO  Service restarted (#{_SERVICE_STATE['restart_count']})")
        return {"ok": True, "status": "running", "restart_count": _SERVICE_STATE["restart_count"]}
    if action == "status":
        return {"ok": True, **_SERVICE_STATE}
    if action == "autostart":
        _SERVICE_STATE["auto_start"] = not _SERVICE_STATE["auto_start"]
        return {"ok": True, "auto_start": _SERVICE_STATE["auto_start"]}
    return {"error": f"未知操作: {action}"}


