# 向导状态（内存）
_WIZARD_STATE: Dict[str, Any] = {
    "current_step": 0,
    "total_steps": len(WIZARD_STEPS),
    "completed_steps": [],
    "config": {},
    "started_at": time.strftime("%Y-%m-%d %H:%M:%S"),
    "finished_at": None,
    "status": "not_started",
}


def get_wizard_status() -> Dict[str, Any]:
    """获取向导当前状态。"""
    steps_detail = []
    for s in WIZARD_STEPS:
        done = s["step"] in _WIZARD_STATE["completed_steps"]
        steps_detail.append({
            "step": s["step"], "key": s["key"], "title": s["title"],
            "description": s["description"], "done": done,
            "active": s["step"] == _WIZARD_STATE["current_step"],
        })
    return {
        **_WIZARD_STATE,
        "steps": steps_detail,
        "progress": round(len(_WIZARD_STATE["completed_steps"]) / len(WIZARD_STEPS) * 100, 1),
    }


def wizard_step_submit(step: int, data: Dict[str, Any]) -> Dict[str, Any]:
    """提交向导某一步的数据。"""
    if step < 1 or step > len(WIZARD_STEPS):
        return {"error": f"无效步骤: {step}"}
    step_key = WIZARD_STEPS[step - 1]["key"]
    _WIZARD_STATE["config"][step_key] = data
    if step not in _WIZARD_STATE["completed_steps"]:
        _WIZARD_STATE["completed_steps"].append(step)
    _WIZARD_STATE["current_step"] = min(step + 1, len(WIZARD_STEPS))
    if len(_WIZARD_STATE["completed_steps"]) == len(WIZARD_STEPS):
        _WIZARD_STATE["status"] = "finished"
        _WIZARD_STATE["finished_at"] = time.strftime("%Y-%m-%d %H:%M:%S")
    else:
        _WIZARD_STATE["status"] = "in_progress"
    return {"ok": True, "step": step, "next_step": _WIZARD_STATE["current_step"],
            "status": _WIZARD_STATE["status"]}


def wizard_reset() -> Dict[str, Any]:
    """重置向导。"""
    _WIZARD_STATE.clear()
    _WIZARD_STATE.update({
        "current_step": 0, "total_steps": len(WIZARD_STEPS),
        "completed_steps": [], "config": {},
        "started_at": time.strftime("%Y-%m-%d %H:%M:%S"),
        "finished_at": None, "status": "not_started",
    })
    return {"ok": True, "message": "向导已重置"}


