REMEDIATION_DB: List[Dict[str, Any]] = [_rm(*t) for t in _REMEDIATIONS]
REMEDIATION_INDEX: Dict[str, Dict[str, Any]] = {r["cve_id"]: r for r in REMEDIATION_DB}


def get_remediation_by_cve(cve_id: str) -> Optional[Dict[str, Any]]:
    if not cve_id:
        return None
    return REMEDIATION_INDEX.get(cve_id.strip().upper())


def list_remediations(page: int = 1, page_size: int = 20) -> Dict[str, Any]:
    total = len(REMEDIATION_DB)
    page = max(1, int(page))
    page_size = max(1, min(500, int(page_size)))
    start = (page - 1) * page_size
    end = start + page_size
    return {
        "total": total, "page": page, "page_size": page_size,
        "total_pages": (total + page_size - 1) // page_size,
        "items": REMEDIATION_DB[start:end],
    }


def search_remediations(keyword=None, vuln_type=None, priority=None):
    kw = (keyword or "").lower().strip()
    vt = (vuln_type or "").strip()
    pr = (priority or "").strip()
    out = []
    for r in REMEDIATION_DB:
        if vt and vt != r["vuln_type"]:
            continue
        if pr and pr != r["fix_priority"]:
            continue
        if kw:
            blob = " ".join([
                r["cve_id"], r["vuln_type"],
                " ".join(r["fix_steps"]),
                r["config_changes"], r["verification_method"],
            ]).lower()
            if kw not in blob:
                continue
        out.append(r)
    return out


