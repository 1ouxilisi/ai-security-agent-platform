_SEEN = set()
CVE_DATABASE: List[Dict[str, Any]] = []
for _t in _RAW:
    rec = _r(*_t)
    cid = rec["cve_id"]
    if cid in _SEEN:
        continue
    _SEEN.add(cid)
    CVE_DATABASE.append(rec)

CVE_INDEX: Dict[str, Dict[str, Any]] = {r["cve_id"]: r for r in CVE_DATABASE}


def get_cve(cve_id: str) -> Optional[Dict[str, Any]]:
    if not cve_id:
        return None
    return CVE_INDEX.get(cve_id.strip().upper())


def search_cve(keyword=None, product=None, vuln_type=None, severity=None,
               cvss_min=None, year=None):
    results = []
    kw = (keyword or "").lower().strip()
    prod = (product or "").lower().strip()
    vt = (vuln_type or "").strip()
    sev = (severity or "").strip().lower()
    for r in CVE_DATABASE:
        if kw:
            blob = " ".join([r["cve_id"], r["title"], r["description"],
                             r["affected_product"], r["affected_version"]]).lower()
            if kw not in blob:
                continue
        if prod and prod not in r["affected_product"].lower():
            continue
        if vt and vt != r["vuln_type"]:
            continue
        if sev and sev != r["severity"]:
            continue
        if cvss_min is not None and r["cvss_score"] < cvss_min:
            continue
        if year is not None:
            try:
                if int(r["published_date"][:4]) != int(year):
                    continue
            except Exception:
                pass
        results.append(r)
    return results


def match_cve_by_service(service_name, version=""):
    if not service_name:
        return []
    s = service_name.lower().strip()
    aliases = {
        "nginx": ["nginx"], "apache": ["apache http", "http server"],
        "httpd": ["apache http", "http server"], "tomcat": ["tomcat"],
        "mysql": ["mysql", "mariadb"], "mariadb": ["mariadb"],
        "redis": ["redis"], "mongodb": ["mongo"], "postgres": ["postgres"],
        "postgresql": ["postgres"], "openssh": ["openssh"], "openssl": ["openssl"],
        "docker": ["docker", "moby", "runc", "containerd"],
        "kube": ["kubernetes"], "k8s": ["kubernetes"],
        "grafana": ["grafana"], "zabbix": ["zabbix"],
        "wordpress": ["wordpress"], "confluence": ["confluence"],
        "gitlab": ["gitlab"], "jenkins": ["jenkins"],
        "log4j": ["log4j"], "spring": ["spring"],
        "php": ["php"], "python": ["python"], "node": ["node.js"],
        "ruby": ["ruby"], "java": ["java", "openjdk"],
        "curl": ["curl", "libcurl"], "firefox": ["firefox"], "chrome": ["chrome"],
    }
    results = []
    for r in CVE_DATABASE:
        prod = r["affected_product"].lower()
        hit = s in prod
        if not hit:
            for k, vals in aliases.items():
                if k in s and any(v in prod for v in vals):
                    hit = True
                    break
        if not hit:
            continue
        if version:
            vs = str(version).strip()
            if vs and vs not in r["affected_version"]:
                m = re.match(r"(\d+)\.(\d+)", vs)
                if m and m.group(1) not in r["affected_version"]:
                    continue
        results.append(r)
    return results


def get_cve_stats():
    by_type = Counter(r["vuln_type"] for r in CVE_DATABASE)
    by_severity = Counter(r["severity"] for r in CVE_DATABASE)
    by_year = Counter(r["published_date"][:4] for r in CVE_DATABASE if r["published_date"])
    by_product = Counter(r["affected_product"] for r in CVE_DATABASE)
    return {
        "total": len(CVE_DATABASE),
        "by_type": dict(by_type),
        "by_severity": dict(by_severity),
        "by_year": dict(sorted(by_year.items())),
        "top_products": [{"product": p, "count": c} for p, c in by_product.most_common(10)],
    }


def list_cves(page=1, page_size=20, sort_by="cvss_score", sort_order="desc"):
    valid_keys = {"cvss_score", "published_date", "cve_id", "severity"}
    key = sort_by if sort_by in valid_keys else "cvss_score"

    def _key(r):
        v = r.get(key, 0)
        return float(v) if key == "cvss_score" else str(v)

    sorted_list = sorted(CVE_DATABASE, key=_key, reverse=(sort_order.lower() == "desc"))
    total = len(sorted_list)
    page = max(1, int(page))
    page_size = max(1, min(500, int(page_size)))
    start = (page - 1) * page_size
    end = start + page_size
    return {
        "total": total, "page": page, "page_size": page_size,
        "total_pages": (total + page_size - 1) // page_size,
        "items": sorted_list[start:end],
    }


