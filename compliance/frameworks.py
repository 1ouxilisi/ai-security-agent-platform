class ComplianceFramework:
    """合规框架库：管理框架元数据、控制项与跨框架映射。"""

    def __init__(self):
        """初始化并幂等建表、批量播种数据。"""
        self._init_tables()
        self._seed_data()

    # ==================== 数据库初始化 ====================

    def _init_tables(self):
        """初始化合规框架相关数据表（幂等）"""
        conn = db._get_connection()
        try:
            cur = conn.cursor()
            cur.execute("""
                CREATE TABLE IF NOT EXISTS cp_frameworks (
                    id INTEGER PRIMARY KEY AUTOINCREMENT,
                    code TEXT UNIQUE NOT NULL,
                    name TEXT NOT NULL,
                    version TEXT,
                    description TEXT,
                    domain_count INTEGER DEFAULT 0,
                    control_count INTEGER DEFAULT 0,
                    created_at TEXT NOT NULL
                )
            """)
            cur.execute("""
                CREATE TABLE IF NOT EXISTS cp_controls (
                    id INTEGER PRIMARY KEY AUTOINCREMENT,
                    framework_id INTEGER NOT NULL,
                    domain TEXT,
                    control_id TEXT NOT NULL,
                    title TEXT,
                    requirement TEXT,
                    test_method TEXT,
                    evidence_requirement TEXT,
                    severity TEXT DEFAULT 'medium',
                    is_automated INTEGER DEFAULT 0,
                    created_at TEXT NOT NULL,
                    FOREIGN KEY (framework_id) REFERENCES cp_frameworks(id)
                )
            """)
            cur.execute("""
                CREATE TABLE IF NOT EXISTS cp_control_mappings (
                    id INTEGER PRIMARY KEY AUTOINCREMENT,
                    control_id TEXT NOT NULL,
                    framework_id INTEGER NOT NULL,
                    mapped_control_id TEXT NOT NULL,
                    notes TEXT
                )
            """)
            cur.execute("CREATE INDEX IF NOT EXISTS idx_cp_controls_fw ON cp_controls(framework_id)")
            cur.execute("CREATE INDEX IF NOT EXISTS idx_cp_controls_sev ON cp_controls(severity)")
            cur.execute("CREATE INDEX IF NOT EXISTS idx_cp_controls_auto ON cp_controls(is_automated)")
            cur.execute("CREATE INDEX IF NOT EXISTS idx_cp_mapping_ctrl ON cp_control_mappings(control_id)")
            conn.commit()
            log.info("✅ 合规框架表初始化完成")
        except Exception as e:
            log.error(f"合规框架表初始化失败: {e}")
        finally:
            conn.close()

    # ==================== 数据播种 ====================

    def _seed_data(self):
        """幂等批量插入框架与控制项（已有数据则跳过）"""
        conn = db._get_connection()
        try:
            cur = conn.cursor()
            existing = cur.execute("SELECT COUNT(*) FROM cp_frameworks").fetchone()[0]
            if existing >= len(FRAMEWORK_META):
                return  # 已播种
            now = datetime.now().isoformat()
            for meta in FRAMEWORK_META:
                rows = CONTROL_DATA.get(meta["code"], [])
                domains = len({r[0] for r in rows})
                cur.execute("""
                    INSERT OR IGNORE INTO cp_frameworks
                        (code, name, version, description, domain_count, control_count, created_at)
                    VALUES (?, ?, ?, ?, ?, ?, ?)
                """, (meta["code"], meta["name"], meta["version"],
                      meta["description"], domains, len(rows), now))
            # 控制项
            fw_id_by_code = {
                r["code"]: r["id"]
                for r in cur.execute("SELECT id, code FROM cp_frameworks").fetchall()
            }
            for code, controls in CONTROL_DATA.items():
                fw_id = fw_id_by_code.get(code)
                if not fw_id:
                    continue
                for (domain, cid, title, req, sev, auto) in controls:
                    cur.execute("""
                        INSERT INTO cp_controls
                            (framework_id, domain, control_id, title, requirement,
                             test_method, evidence_requirement, severity, is_automated, created_at)
                        VALUES (?, ?, ?, ?, ?, ?, ?, ?, ?, ?)
                    """, (fw_id, domain, cid, title, req,
                          _DEFAULT_TEST_METHOD.get(sev, _DEFAULT_TEST_METHOD["medium"]),
                          _DEFAULT_EVIDENCE.get(sev, _DEFAULT_EVIDENCE["medium"]),
                          sev, 1 if auto else 0, now))
            # 映射
            for (cid, code, mapped_cid, notes) in MAPPING_DATA:
                fw_id = fw_id_by_code.get(code)
                if fw_id:
                    cur.execute("""
                        INSERT INTO cp_control_mappings
                            (control_id, framework_id, mapped_control_id, notes)
                        VALUES (?, ?, ?, ?)
                    """, (cid, fw_id, mapped_cid, notes))
            conn.commit()
            total_ctrl = cur.execute("SELECT COUNT(*) FROM cp_controls").fetchone()[0]
            log.info(f"✅ 合规框架数据播种完成：{len(FRAMEWORK_META)} 框架，{total_ctrl} 控制项")
        except Exception as e:
            log.error(f"合规框架数据播种失败: {e}")
        finally:
            conn.close()

    # ==================== 查询方法 ====================

    def list_frameworks(self) -> List[dict]:
        """获取所有框架列表（含控制项数量）"""
        conn = db._get_connection()
        try:
            rows = conn.execute("""
                SELECT f.*,
                       (SELECT COUNT(*) FROM cp_controls c WHERE c.framework_id = f.id) AS ctrl_total,
                       (SELECT COUNT(DISTINCT domain) FROM cp_controls c WHERE c.framework_id = f.id) AS domain_total
                FROM cp_frameworks f ORDER BY f.id
            """).fetchall()
            result = []
            for r in rows:
                item = dict(r)
                item["control_count"] = item.get("ctrl_total", item.get("control_count", 0))
                item["domain_count"] = item.get("domain_total", item.get("domain_count", 0))
                result.append(item)
            return result
        finally:
            conn.close()

    def get_framework(self, framework_id: int) -> Optional[dict]:
        """框架详情"""
        conn = db._get_connection()
        try:
            row = conn.execute("SELECT * FROM cp_frameworks WHERE id = ?",
                               (framework_id,)).fetchone()
            return dict(row) if row else None
        finally:
            conn.close()

    def list_controls(self, framework_id: int, domain: str = None,
                     severity: str = None, is_automated: bool = None,
                     page: int = 1, page_size: int = 20) -> dict:
        """按框架获取控制项列表，支持筛选与分页"""
        where = "WHERE framework_id = ?"
        params: list = [framework_id]
        if domain:
            where += " AND domain = ?"
            params.append(domain)
        if severity:
            where += " AND severity = ?"
            params.append(severity)
        if is_automated is not None:
            where += " AND is_automated = ?"
            params.append(1 if is_automated else 0)
        conn = db._get_connection()
        try:
            total = conn.execute(f"SELECT COUNT(*) FROM cp_controls {where}", params).fetchone()[0]
            page = max(1, page)
            page_size = max(1, min(200, page_size))
            offset = (page - 1) * page_size
            rows = conn.execute(
                f"SELECT * FROM cp_controls {where} ORDER BY control_id LIMIT ? OFFSET ?",
                params + [page_size, offset]).fetchall()
            return {
                "total": total, "page": page, "page_size": page_size,
                "total_pages": (total + page_size - 1) // page_size if page_size else 0,
                "items": [dict(r) for r in rows],
            }
        finally:
            conn.close()

    def get_control(self, control_id: int) -> Optional[dict]:
        """控制项详情"""
        conn = db._get_connection()
        try:
            row = conn.execute("SELECT * FROM cp_controls WHERE id = ?",
                               (control_id,)).fetchone()
            return dict(row) if row else None
        finally:
            conn.close()

    def get_control_mappings(self, framework_id: int,
                             control_code: str = None) -> List[dict]:
        """获取控制项跨框架映射"""
        conn = db._get_connection()
        try:
            where = "WHERE framework_id = ?"
            params: list = [framework_id]
            if control_code:
                where += " AND control_id = ?"
                params.append(control_code)
            rows = conn.execute(
                f"SELECT * FROM cp_control_mappings {where}", params).fetchall()
            return [dict(r) for r in rows]
        finally:
            conn.close()

    def search_controls(self, keyword: str, framework_id: int = None,
                        limit: int = 50) -> List[dict]:
        """按关键词搜索控制项（标题/要求/编号）"""
        where = "WHERE (title LIKE ? OR requirement LIKE ? OR control_id LIKE ?)"
        kw = f"%{keyword}%"
        params: list = [kw, kw, kw]
        if framework_id:
            where += " AND framework_id = ?"
            params.append(framework_id)
        conn = db._get_connection()
        try:
            rows = conn.execute(
                f"SELECT * FROM cp_controls {where} ORDER BY control_id LIMIT ?",
                params + [limit]).fetchall()
            return [dict(r) for r in rows]
        finally:
            conn.close()

    def get_framework_stats(self, framework_id: int) -> dict:
        """按框架统计控制项数量/符合率（需关联评估结果表，缺失时返回0）"""
        conn = db._get_connection()
        try:
            total = conn.execute(
                "SELECT COUNT(*) FROM cp_controls WHERE framework_id = ?",
                (framework_id,)).fetchone()[0]
            by_sev = {}
            for sev in SEVERITIES:
                by_sev[sev] = conn.execute(
                    "SELECT COUNT(*) FROM cp_controls WHERE framework_id=? AND severity=?",
                    (framework_id, sev)).fetchone()[0]
            auto = conn.execute(
                "SELECT COUNT(*) FROM cp_controls WHERE framework_id=? AND is_automated=1",
                (framework_id,)).fetchone()[0]
            # 符合率：若评估结果表存在则统计
            compliant = 0
            try:
                compliant = conn.execute("""
                    SELECT COUNT(*) FROM cp_assessment_results r
                    JOIN cp_assessments a ON r.assessment_id = a.id
                    JOIN cp_controls c ON r.control_id = c.id
                    WHERE a.framework_id = ? AND r.status = 'compliant'
                """, (framework_id,)).fetchone()[0]
            except sqlite3.OperationalError:
                pass
            return {
                "framework_id": framework_id,
                "total_controls": total,
                "by_severity": by_sev,
                "automated": auto,
                "compliant": compliant,
                "compliance_rate": round(compliant / total * 100, 2) if total else 0.0,
            }
        finally:
            conn.close()

    def create_custom_control(self, framework_id: int, domain: str,
                              control_id: str, title: str, requirement: str,
                              test_method: str = "", evidence_requirement: str = "",
                              severity: str = "medium",
                              is_automated: bool = False) -> Optional[int]:
        """创建自定义控制项"""
        now = datetime.now().isoformat()
        conn = db._get_connection()
        try:
            cur = conn.execute("""
                INSERT INTO cp_controls
                    (framework_id, domain, control_id, title, requirement,
                     test_method, evidence_requirement, severity, is_automated, created_at)
                VALUES (?, ?, ?, ?, ?, ?, ?, ?, ?, ?)
            """, (framework_id, domain, control_id, title, requirement,
                  test_method, evidence_requirement, severity,
                  1 if is_automated else 0, now))
            conn.commit()
            return cur.lastrowid
        except Exception as e:
            log.error(f"创建自定义控制项失败: {e}")
            return None
        finally:
            conn.close()

    def update_control(self, control_pk: int, **kwargs) -> bool:
        """更新控制项（支持自定义控制项）"""
        allowed = ("domain", "title", "requirement", "test_method",
                   "evidence_requirement", "severity", "is_automated")
        sets, params = [], []
        for k, v in kwargs.items():
            if k in allowed:
                sets.append(f"{k} = ?")
                params.append(v)
        if not sets:
            return False
        params.append(control_pk)
        conn = db._get_connection()
        try:
            conn.execute(f"UPDATE cp_controls SET {', '.join(sets)} WHERE id = ?", params)
            conn.commit()
            return True
        except Exception as e:
            log.error(f"更新控制项失败: {e}")
            return False
        finally:
            conn.close()


